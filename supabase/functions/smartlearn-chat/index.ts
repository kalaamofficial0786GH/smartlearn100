import { serve } from "https://deno.land/std@0.168.0/http/server.ts";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers":
    "authorization, x-client-info, apikey, content-type, x-supabase-client-platform, x-supabase-client-platform-version, x-supabase-client-runtime, x-supabase-client-runtime-version",
};

const SYSTEM_PROMPT = `You are SmartLearn AI Assistant — a friendly, helpful learning companion for the SmartLearn online education platform.

Your purpose:
- Help students understand course topics (HTML, CSS, JavaScript, React, Python, Node.js, Flutter, Git, UI/UX, MongoDB, Data Structures, etc.)
- Explain programming concepts with simple examples
- Suggest relevant SmartLearn courses
- Guide users on how to use the platform (enroll, navigate, access videos)
- Support both English and Tamil languages — if a user writes in Tamil, respond in Tamil

Platform info:
- All courses are FREE
- Courses are available in English and Tamil
- To enroll: Open a course → Click Enroll → Enter registered email → Start learning
- Available categories: Programming, Web Development, AI/ML, Mobile Dev, Computer Basics, Software Tools, Editing

Behavior:
- Keep answers concise and beginner-friendly
- Use code examples when explaining programming concepts (use markdown code blocks)
- When suggesting courses, list them as bullet points
- If you don't know something, say "I'm still learning. Please try asking in a different way."
- Be encouraging and supportive of learners`;

serve(async (req) => {
  if (req.method === "OPTIONS") {
    return new Response(null, { headers: corsHeaders });
  }

  try {
    const { messages } = await req.json();
    const LOVABLE_API_KEY = Deno.env.get("LOVABLE_API_KEY");
    if (!LOVABLE_API_KEY) throw new Error("LOVABLE_API_KEY is not configured");

    const response = await fetch(
      "https://ai.gateway.lovable.dev/v1/chat/completions",
      {
        method: "POST",
        headers: {
          Authorization: `Bearer ${LOVABLE_API_KEY}`,
          "Content-Type": "application/json",
        },
        body: JSON.stringify({
          model: "google/gemini-3-flash-preview",
          messages: [
            { role: "system", content: SYSTEM_PROMPT },
            ...messages,
          ],
          stream: true,
        }),
      }
    );

    if (!response.ok) {
      if (response.status === 429) {
        return new Response(
          JSON.stringify({ error: "Rate limit exceeded. Please try again shortly." }),
          { status: 429, headers: { ...corsHeaders, "Content-Type": "application/json" } }
        );
      }
      if (response.status === 402) {
        return new Response(
          JSON.stringify({ error: "AI credits exhausted. Please add credits." }),
          { status: 402, headers: { ...corsHeaders, "Content-Type": "application/json" } }
        );
      }
      const t = await response.text();
      console.error("AI gateway error:", response.status, t);
      return new Response(
        JSON.stringify({ error: "AI service error" }),
        { status: 500, headers: { ...corsHeaders, "Content-Type": "application/json" } }
      );
    }

    return new Response(response.body, {
      headers: { ...corsHeaders, "Content-Type": "text/event-stream" },
    });
  } catch (e) {
    console.error("chat error:", e);
    return new Response(
      JSON.stringify({ error: e instanceof Error ? e.message : "Unknown error" }),
      { status: 500, headers: { ...corsHeaders, "Content-Type": "application/json" } }
    );
  }
});
